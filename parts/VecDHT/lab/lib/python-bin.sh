#!/bin/bash
# python-bin.sh — один выбор интерпретатора на весь репозиторий (F-0076, F-0077).
#
# Зачем: пять скриптов звали `python`, которого в окружении без Python 2 нет (WSL Ubuntu даёт
# только python3). Каждый такой вызов падал с 127 «command not found», а приборы считали
# ненулевой код провалом проверки. Так «не запустилось» превращалось в «провалилось»:
# в блоке E-0178 от 22:16 таких кодов было 54, и VERIFY_FAIL=1 читался как провал тестов,
# хотя cargo test и clippy были зелёные.
#
# Контракт: PY_BIN — путь к интерпретатору. Если его нет вовсе, скрипт обязан выйти с кодом 2
# («проверка не запускалась»), а не с 1 («провалилась»). Это тот же контракт трёх исходов,
# что в H-0179 для стража текста.
#
# Употребление:
#   . "$(dirname "$0")/lib/python-bin.sh"      # из lab/*.sh
#   "$PY_BIN" lab/facts.py repro ...
#
# Обёртка `python()` тоже определена — для скриптов, которые зовут python внутри циклов и
# функций и не переписаны. Новый код обязан звать "$PY_BIN", а не обёртку.

PY_BIN=""
for _candidate in python3 python; do
  if command -v "$_candidate" > /dev/null 2>&1; then PY_BIN="$_candidate"; break; fi
done
unset _candidate

if [ -z "$PY_BIN" ]; then
  echo "python-bin: нет ни python3, ни python — проверка не запускалась (это не провал объекта)" >&2
  exit 2
fi

# Обёртка для непереписанного кода. Не наследуется дочерними процессами: скрипт, который
# запускают через bash, обязан подключить этот файл сам (ровно на этом сломался lean-check.sh).
python() { "$PY_BIN" "$@"; }
