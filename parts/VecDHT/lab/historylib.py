# lab/historylib.py — общий механизм «полна ли история, по которой судит прибор» (ADR-0079, E-0173).
"""Один признак, один вопрос, один ответ.

Прибор, который выводит дату появления файла из git-истории (`git log --diff-filter=A`) или судит о
дате по наличию записи в истории, обязан спросить этот механизм до первого числа: в клоне глубиной
один коммит все файлы выглядят добавленными сегодня, и вердикт получается выдуманным, а не измеренным.

Граница механизма названа в `ADR-0079`: признак `--is-shallow-repository` ставит сама среда по
глубине клона; `graft`, `--since` и обрезанный `replace-ref` им не ловятся и остаются названным
остатком, а не молчаливой дырой.
"""
import os
import subprocess

# Отказ отличается от красного выхода именно смыслом: 1 — «есть находки в дереве», 3 — «я не могу
# судить, потому что данных нет». Смешивать их нельзя: вызывающий обязан видеть причину.
EXIT_REFUSED = 3


def is_shallow(root=None):
    """True, если история клона неполна (глубина ограничена). Ошибка git = не отказ."""
    out = subprocess.run(["git", "-C", root or os.getcwd(), "rev-parse", "--is-shallow-repository"],
                         capture_output=True, text=True)
    return out.returncode == 0 and out.stdout.strip() == "true"


def refuse(tag, root_kind="shallow"):
    """Печатает форму отказа и возвращает код отказа.

    Строка вердикта здесь не печатается намеренно: прибор, освобождающий себя числом (`0` находок
    по несуществующей истории), неотличим от прибора, который нашёл ноль на самом деле — это ровно класс
    самоосвобождения, найденный `E-0167` и `E-0172`.
    """
    print("%s_SHALLOW=1" % tag)
    print("%s_ROOT_KIND=%s" % (tag, root_kind))
    return EXIT_REFUSED
