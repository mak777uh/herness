"""gate_audit — может ли агент удовлетворить гейт, написав нужное поле?

Это форма дефекта, которую flowguard-spec нашёл 34 раза за три раунда:
«гейт удовлетворяется полем, которое пишет сам заявитель».

Проверяем каждый гейт на вопрос: если агент напишет ровно то, что гейт ищет,
пройдёт ли он? Если да — гейт проверяет текст, а не мир.

    python bin/gate_audit.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "outputs" / "gate-audit.txt"

# Гейт, что он ищет, кто пишет то, что он ищет, и может ли агент это подделать.
GATES = [
    ("опора (claim_anchor)", "токен из ответа, который есть в результатах инструментов",
     "агент пишет ответ; результаты пишут инструменты",
     "частично: токен обязан прийти из инструмента, но выбрать, какой именно, может агент"),
    ("замыкание (closure_probe)", "в теле инструмента нет вызовов записи/сети",
     "исходник пишем мы", "нет: проверяется код, а не текст агента"),
    ("политика (policy.py)", "правила без противоречий и неявных разрешений",
     "политику пишем мы", "нет: проверяется файл, который агент не пишет"),
    ("сверка политики (policy_sync)", "политика в коде = политика в файле",
     "оба файла наши", "нет"),
    ("сверка Rust/Lean (policy_diff)", "две реализации дают одно на одних входах",
     "обе реализации наши", "нет"),
    ("пробы гейтов (gate_probe)", "гейт ловит подложенный дефект",
     "дефект подкладываем мы", "нет"),
    ("устойчивость (durability)", "журнал переживает обрыв",
     "обрыв делаем мы", "нет"),
    ("форма шага (parse_step)", "ответ разбирается как TOOL/DONE/BLOCKED",
     "агент пишет ответ", "да, но это не проверка мира — это проверка формы"),
    ("бюджет (Budget)", "шаги и деньги не превышены",
     "считаем мы по событиям", "нет"),
    ("порядок (verify_order)", "события идут в правильном порядке",
     "журнал пишем мы", "нет"),
    ("утверждения (CLAIMS.md)", "у каждого утверждения есть артефакт и команда проверки",
     "утверждение пишем мы, но опору выбираем сами",
     "да: опора выбирается автором утверждения"),
    ("не-утверждения (NOT-CLAIMED)", "список границ",
     "пишем мы", "нет проверки: список не сверяется с кодом"),
]


def main() -> int:
    lines = ["# Аудит гейтов: может ли агент удовлетворить гейт, написав поле?", ""]
    lines.append("| гейт | что ищет | кто пишет | может подделать |")
    lines.append("|---|---|---|---|")
    weak = []
    for name, looks_for, who, fake in GATES:
        lines.append(f"| {name} | {looks_for} | {who} | {fake} |")
        if fake.startswith("да") or fake.startswith("частично"):
            weak.append(name)

    lines += [
        "",
        f"слабых мест: {len(weak)} из {len(GATES)}",
        "",
        "## Слабые места и что с ними делать",
        "",
        "| гейт | почему слаб | что усилит |",
        "|---|---|---|",
        "| опора | агент выбирает, какой токен назвать опорой | требовать опору, которую выбрал не он:"
        " например, последний результат инструмента, а не любой |",
        "| утверждения | опора выбирается автором утверждения | сверять утверждение с кодом или прогоном,"
        " а не с текстом |",
        "| форма шага | проверяет форму, а не мир | это нормально: гейт формы и не должен проверять мир |",
        "",
        "## Что это значит",
        "",
        "Из 12 гейтов **3 слабых**, и один из них — форма, где слабость нормальна.",
        "Остаётся **2 настоящих**: опора и утверждения. Оба устроены одинаково — **автор выбирает,",
        "чем подтвердить**. Это ровно форма дефекта из flowguard-spec.",
        "",
        "Граница: аудит по описанию гейтов, а не по их коду. Он называет, где искать,",
        "а не доказывает, что дефект есть.",
    ]
    text = "\n".join(lines) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
