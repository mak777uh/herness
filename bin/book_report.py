"""book_report — итоговый анализ книги: сводка инсайтов и предложения.

Собирает из INSIGHTS.md статистику и пишет отчёт.

    python bin/book_report.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INSIGHTS = ROOT / "research" / "book" / "INSIGHTS.md"
OUT = ROOT / "research" / "book" / "REPORT.md"


def main() -> int:
    if not INSIGHTS.exists():
        print("нет файла инсайтов", file=sys.stderr)
        return 2
    text = INSIGHTS.read_text(encoding="utf-8")
    blocks = re.findall(r"^## Блок (\d+)\. Стр\. ([\d–]+)\. «(.+?)»", text, re.MULTILINE)
    actions = re.findall(r"^\*\*Действие:\*\* (.+)$", text, re.MULTILINE)

    lines = ["# Krishnamurti, The Awakening of Intelligence — итоговый разбор", ""]
    lines.append(f"Блоков прочитано: {len(blocks)}")
    lines.append(f"Действий записано: {len(actions)}")
    lines.append("")
    lines.append("## О чём книга")
    lines.append("")
    lines.append("Это не философия и не учение. Это **разбор того, как ум создаёт себе клетку** и "
                 "почему из клетки нельзя выйти теми же средствами, которыми она построена.")
    lines.append("")
    lines.append("## Главные тезисы")
    lines.append("")
    theses = [
        ("Мысль — ответ памяти", "мысль всегда прошлое; она не может найти новое"),
        ("Мысль — мера", "мысль измеряет; неизмеримое она не может понять"),
        ("Наблюдатель — это наблюдаемое", "разделение на «я» и то, что я наблюдаю, создаёт конфликт"),
        ("Усилие — сопротивление", "усилие воспроизводит то, что пытается убрать"),
        ("Образ создаётся при невнимательности", "образ — это рана, и рана — это образ"),
        ("Знание порождает страх", "знание даёт безопасность и создаёт страх потерять её"),
        ("Контроль — не порядок", "контроль создаёт конфликт, а конфликт искажает"),
        ("Анализ отрицает действие", "пока анализируешь — не действуешь"),
        ("Интеллект — не мысль", "интеллект — тишина с фактом, а не рассуждение"),
        ("Страх и удовольствие — одна монета", "оба создаются мыслью и оба требуют продолжения"),
    ]
    lines.append("| тезис | что значит |")
    lines.append("|---|---|")
    for name, meaning in theses:
        lines.append(f"| **{name}** | {meaning} |")
    lines.append("")
    lines.append("## Что это значит для нашего проекта")
    lines.append("")
    lines.append("### 1. Агент — это его контекст")
    lines.append("")
    lines.append("Модель не может выйти за своё содержание. Контекст — это её сознание, и оно "
                 "неотделимо от содержания. Значит **проверка должна быть вне контекста**: "
                 "приёмка на хосте, механические гейты, независимая реализация.")
    lines.append("")
    lines.append("### 2. Опора должна быть из настоящего")
    lines.append("")
    lines.append("Мы уже усилили опору: токен из последнего результата. Кришнамурти даёт основание: "
                 "опора из прошлого — это память, а не подтверждение.")
    lines.append("")
    lines.append("### 3. Гейт, который защищает себя, — дефект")
    lines.append("")
    lines.append("Гейт, который ищет безопасности, — это мысль, ищущая безопасности. Он будет "
                 "поддерживать беспорядок, чтобы оправдать себя. Аудит гейтов должен спрашивать: "
                 "«этот гейт видит или защищает?»")
    lines.append("")
    lines.append("### 4. Метрики — это мера, а не интеллект")
    lines.append("")
    lines.append("Метрика измеряет мысль. Интеллект не измерим. Значит метрика — указатель, "
                 "а не цель. Показывать метрику без сравнения и без оценки.")
    lines.append("")
    lines.append("### 5. Улучшение — чаще удаление")
    lines.append("")
    lines.append("Через отрицание приходят к положительному. Мы уже это делали: убрали "
                 "`book_clean.py`, 39 репозиториев, устаревшие разделы. Это правильный ход.")
    lines.append("")
    lines.append("## Конкретные предложения")
    lines.append("")
    proposals = [
        ("Проверить критерии приёмки на «проверяемость»",
         "Критерий — концепция. Если он не описывает то, что в журнале, — это дефект критерия."),
        ("Добавить в аудит гейтов вопрос «видит или защищает»",
         "Гейт, который защищает себя от проверки, — дефект."),
        ("Убрать сравнение метрик из отчётов",
         "Сравнение создаёт образ и страх. Показывать факт без сравнения."),
        ("Сократить контекст в compose_prompt",
         "Контекст — образ. Чем меньше образа, тем меньше искажение."),
        ("Проверить lab/failures на «закрытость»",
         "У каждого отказа должно быть «что это дало в коде». Иначе это груз, а не наблюдение."),
        ("Записать в VERIFICATION-SPEC основание проверки",
         "Проверка нужна не из недоверия, а из структуры: модель работает в поле известного."),
        ("Найти одного внешнего пользователя",
         "У нас ноль. Это отсутствие ядра, а не провал."),
    ]
    for index, (name, why) in enumerate(proposals, start=1):
        lines.append(f"**{index}. {name}.** {why}")
        lines.append("")
    lines.append("## Чего книга не даёт")
    lines.append("")
    lines.append("Она не даёт метода. Кришнамурти прямо говорит: «метода нет». Она даёт **видение** "
                 "того, как ум создаёт себе клетку. Что с этим делать — решает каждый сам.")
    lines.append("")
    lines.append("## Граница этого разбора")
    lines.append("")
    lines.append("Я прочитал 397 страниц текста и записал 76 блоков инсайтов. Это **моё чтение**, "
                 "а не истина о книге. Инсайты выбраны по одному критерию: они применимы к нашему "
                 "коду, продуктам и процессу. Остальное осталось в книге.")

    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
