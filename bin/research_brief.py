def render(name: str) -> str:
    spec = TOOLS[name]
    return HEADER.format(name=name, current=spec["current"], questions=spec["questions"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="задание на ресёрч по инструменту")
    parser.add_argument("tool", nargs="?", help="имя инструмента")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--write", action="store_true", help="сохранить в research/")
    args = parser.parse_args(argv if argv is not None else sys.argv[1:])
    if args.list:
        print("\n".join(TOOLS))
        return 0
    if not args.tool or args.tool not in TOOLS:
        print(f"нужно имя из: {', '.join(TOOLS)}", file=sys.stderr)
        return 2
    text = render(args.tool)
    if args.write:
        path = ROOT / "research" / f"P37-{args.tool.upper()}-BRIEF.md"
        path.write_text(text, encoding="utf-8")
        print(f"записано: {path.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
